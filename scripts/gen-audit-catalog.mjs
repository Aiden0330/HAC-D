#!/usr/bin/env node
/** Generate packages/core/src/mechanisms/auditCatalog.ts from packages/core/data/mechanism-audit.json (the user's mechanism audit, review 02, 2026-10-14). */
import { readFileSync, writeFileSync } from 'node:fs';
const src = 'packages/core/data/mechanism-audit.json';
const data = JSON.parse(readFileSync(src, 'utf8'));
const ls = new RegExp(String.fromCharCode(0x2028), 'g');
const ps = new RegExp(String.fromCharCode(0x2029), 'g');
const body = JSON.stringify(data, null, 1).replace(ls, '\\u2028').replace(ps, '\\u2029');
const out = `/* Generated by scripts/gen-audit-catalog.mjs from ${src} (${data.version}, ${data.date}); do not edit by hand. */
/* eslint-disable */
import type { AuditCatalog } from './auditTypes.js';
export const AUDIT_CATALOG: AuditCatalog = ${body} as unknown as AuditCatalog;
`;
writeFileSync('packages/core/src/mechanisms/auditCatalog.ts', out);
console.log(`wrote auditCatalog.ts (${(out.length / 1024).toFixed(0)} kB, ${data.mechanisms.length} mechanisms)`);
